const assert=require('node:assert/strict');
const E=require('./dist/engine.js');
assert.equal(E.sizeOption({capital:2000,riskPct:1,budget:300,ask:1,multiplier:100}),0);
assert.equal(E.sizeOption({capital:2000,riskPct:10,budget:300,buyingPower:150,ask:1,multiplier:100}),1);
assert.equal(E.sizeOption({capital:2000,riskPct:10,budget:300,buyingPower:0,ask:1,multiplier:100}),0);
assert.equal(E.sizeOption({capital:2000,riskPct:1,budget:300,ask:.20,multiplier:100}),1);
assert.equal(E.sizeOption({capital:2000,riskPct:1,budget:300,ask:NaN,multiplier:100}),0);
const bars=Array.from({length:26},(_,i)=>({timestamp:new Date(Date.parse('2026-09-09T13:30:00Z')+i*900000).toISOString(),open:100,high:i===25?999:101,low:99,close:100,volume:10,vwap:100}));
assert.equal(E.levels(bars).high,101,'last candle excluded from breakout range');
assert.equal(E.indicators(bars).rsi[25],50,'flat RSI defined as neutral');
assert.equal(E.indicators(bars).fast[25],100);
assert.equal(E.levels(bars).orbHigh,101);
assert.equal(E.session('2026-01-02T14:30:00Z').minute,570,'winter EST');
assert.equal(E.session('2026-07-02T13:30:00Z').minute,570,'summer EDT');
const next={...bars[0],timestamp:'2026-09-10T13:30:00Z',open:200,high:201,low:199,close:200,vwap:200};
assert.equal(E.indicators([...bars,next]).vwap.at(-1),200,'VWAP resets each session');
const sample={schemaVersion:1,capturedAt:'2026-09-10T10:00:00Z',bars:{TEST:bars},contracts:[],fills:[]};
assert.equal(E.validate(sample),sample);
assert.throws(()=>E.validate({...sample,bars:{TEST:[bars[1],bars[0]]}}));
assert.throws(()=>E.validate({...sample,bars:{TEST:[{...bars[0],high:90}]}}));
console.log('14 risk, indicator, session and import assertions passed.');
